import Foundation

// Compile templates into both executables: runtime never reads a mutable template file.
let source = URL(fileURLWithPath: CommandLine.arguments[1])
let destination = URL(fileURLWithPath: CommandLine.arguments[2])
let files = [
    ("sslocal", "sslocal.json"), ("coreDNS", "Corefile"), ("packetFilter", "pf.conf"),
    ("directDomains", "DNS/direct-domains.txt"), ("bogusResponses", "DNS/bogus-responses.txt"),
    ("appleDomains", "DNS/apple-domains.txt"), ("biliDomains", "DNS/bili-domains.txt")
]
var output = "// Generated by Tools/EmbedTemplates.swift.\nenum ConfigurationTemplates {\n"
for (name, path) in files {
    let content = try String(contentsOf: source.appendingPathComponent(path), encoding: .utf8)
    output += "    static let \(name) = \(String(reflecting: content))\n"
}
output += "}\n"
try output.write(to: destination, atomically: true, encoding: .utf8)
